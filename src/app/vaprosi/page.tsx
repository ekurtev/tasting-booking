import type { Metadata } from "next";
import Link from "next/link";
import { ALLERGEN_NOTICE } from "@/content/company";
import { CANCEL_CUTOFF_HOURS } from "@/lib/booking";
import { getContact } from "@/lib/contact";

export const metadata: Metadata = {
  title: "Често задавани въпроси",
  description: "Отговори за отказ от резервация, детски събития, офис дегустации, плащане и алергени.",
  alternates: { canonical: "/vaprosi" },
};

export default async function FaqPage() {
  const c = await getContact();
  const phone = <a href={`tel:${c.phoneHref}`}>{c.phone}</a>;
  const faq: { q: string; a: React.ReactNode }[] = [
    {
      q: "Как да откажа резервацията си?",
      a: (
        <>
          Отворете личния линк, който получихте след резервацията, и натиснете „Откажи резервацията“. Онлайн
          отказ е възможен до {CANCEL_CUTOFF_HOURS} часа преди началото и е безплатен.
        </>
      ),
    },
    {
      q: `А ако остават по-малко от ${CANCEL_CUTOFF_HOURS} часа?`,
      a: <>Тогава онлайн отказ не е възможен — моля, обадете ни се на {phone} възможно най-рано.</>,
    },
    {
      q: "Как протичат детските рождени дни?",
      a: (
        <>
          Носим подходящи за деца сладки и изненади. През цялото време на събитието трябва да присъства родител
          или друг отговорен възрастен, който се грижи за децата. Резервацията се прави от пълнолетно лице.
        </>
      ),
    },
    {
      q: "Идвате ли в офиса ни?",
      a: (
        <>
          Да — изберете „Офис дегустация за екип“. Посочете приблизителния брой гости, за да подготвим
          достатъчно кутии, а в бележката — адреса на офиса и как да влезем.
        </>
      ),
    },
    {
      q: "Как се плаща?",
      a: <>На място, при дегустацията, в брой или с карта. Цените са в евро с включен ДДС. Онлайн не плащате нищо.</>,
    },
    {
      q: "Има ли алергени в кутиите?",
      a: (
        <>
          {ALLERGEN_NOTICE} Обадете ни се на {phone} — ще ви кажем какво съдържа всяка кутия. От съображения за
          поверителност не събираме данни за алергии във формуляра.
        </>
      ),
    },
    {
      q: "Какви данни пазите за мен?",
      a: (
        <>
          Само данните от резервацията, за 12 месеца след дегустацията — след това се анонимизират. Подробности
          в <Link href="/poveritelnost">Политиката за поверителност</Link>.
        </>
      ),
    },
  ];
  return (
    <>
      <h1>Често задавани въпроси</h1>
      <div className="faq">
        {faq.map((f) => (
          <details key={f.q}>
            <summary>{f.q}</summary>
            <p>{f.a}</p>
          </details>
        ))}
      </div>
    </>
  );
}
